"""The 25 scripts in the free Say This Instead Starter Playbook. No em dashes anywhere."""

SECTIONS = [
    ("Raises and salary", "#BE861C", [
        dict(when="You want a raise",
             dont="\"I was wondering if maybe there's any room for a raise?\"",
             say="\"I'd like to talk about my pay. Over the last six months I took over the client reporting and cut our turnaround from five days to two. Based on that and what this role pays in the market, I'm asking for a move to $X. What would it take to get there?\"",
             why="Results first, a specific number, then a question that makes them problem-solve with you."),
        dict(when="They ask for your salary expectations first",
             dont="\"Whatever you think is fair.\"",
             say="\"I'm focused on the right fit first. For roles with this scope, I'm seeing a range of $X to $Y. Does that line up with what you have budgeted?\"",
             why="A researched range anchors the talk without boxing you into the low end."),
        dict(when="The offer comes in low",
             dont="\"Oh, okay. I guess that works.\"",
             say="\"Thank you, I'm excited about this. The number is below what I expected for this scope. If we could get the base to $X, I'd be ready to sign this week. Is there flexibility there?\"",
             why="Enthusiasm plus a clear number plus a reason for them to move now."),
        dict(when="They say there's no budget",
             dont="\"I understand, never mind.\"",
             say="\"That makes sense. If the base can't move right now, can we agree on a review in 90 days with clear targets, and look at a title change or extra PTO in the meantime?\"",
             why="A no on budget is rarely a no on everything. You keep the door open with dates."),
        dict(when="You find out a coworker earns more for the same job",
             dont="\"It's not fair that she makes more than me.\"",
             say="\"I've done some research on pay for my role and I believe I'm below the market range. I'd like to walk you through my results this year and talk about getting my pay in line.\"",
             why="You make the case about your value and the market, never about a coworker."),
    ]),
    ("Bosses, meetings and remote work", "#DC604E", [
        dict(when="Your mind goes blank in a meeting",
             dont="\"Sorry, I'm not sure, I don't know.\"",
             say="\"Good question. I want to give you a real answer, not a guess. Let me pull the numbers and send them to you by 3 today.\"",
             why="You sound in control, and you set a deadline you can actually hit."),
        dict(when="Your boss pings you at 9pm",
             dont="\"So sorry, on it now!\" (at 9:02pm)",
             say="(Next morning) \"Morning! Saw your message from last night. I'll have this to you by 11. For anything urgent after hours, a call works best so I don't miss it.\"",
             why="You answer fast during the day and quietly teach what after-hours really means."),
        dict(when="Someone takes credit for your idea",
             dont="\"Um, actually that was my idea.\"",
             say="\"Thanks for bringing that up. When I first proposed this last week, the next step I had in mind was X. Want me to take the lead on that?\"",
             why="You claim it calmly, out loud, and turn it into ownership instead of a fight."),
        dict(when="Your camera has to stay off",
             dont="\"Sorry, my camera's being weird.\"",
             say="\"Quick heads up, I'm keeping my camera off for this one so I can focus, but I'm fully here. Happy to jump on video for the next call.\"",
             why="Honest, short, and it shows you're engaged without over-explaining."),
        dict(when="You need feedback on work you sent",
             dont="\"Just checking in on this!\"",
             say="\"I want to make sure this is ready for Thursday. Are there any parts you'd like me to change before then?\"",
             why="A deadline and a direct question get answers. \"Just checking in\" gets ignored."),
    ]),
    ("Boundaries and saying no", "#4A6FA5", [
        dict(when="You're asked to take on more work",
             dont="\"Sure, no problem!\" (already drowning)",
             say="\"I want to do this well. Right now I'm on X and Y for Friday. If I take this on, which one should move?\"",
             why="You say yes to the work and make the trade-off their decision."),
        dict(when="Someone keeps booking calls that could be a message",
             dont="Accepting every invite.",
             say="\"Happy to help with this. To save us both time, could you send me the questions here first? If it still needs a call after that, I'll grab 15 minutes.\"",
             why="You protect your focus time without saying no to the person."),
        dict(when="A coworker keeps asking you to cover",
             dont="\"Ugh, okay, one more time.\"",
             say="\"I can't cover this one, I'm at capacity this week. Next time, give me a heads up a few days early and I'll see what I can do.\"",
             why="A clear no today and a fair rule for next time."),
        dict(when="You're asked to work your day off",
             dont="\"I mean, I guess I could.\"",
             say="\"I'm not available Saturday. I can get it done first thing Monday, or I can hand my part to someone today so it keeps moving. Which works better?\"",
             why="Firm on the boundary, generous with options."),
        dict(when="You need to log off on time",
             dont="Staying online until someone notices.",
             say="\"I'm signing off at 5 today. Here's where things stand: X is done, Y goes out first thing tomorrow. Message me here and I'll pick it up in the morning.\"",
             why="A clean handoff makes logging off look professional, not lazy."),
    ]),
    ("Clients, pricing and invoices", "#6C8F4E", [
        dict(when="A client says your price is too high",
             dont="\"I can do it cheaper.\"",
             say="\"I hear you. Too high compared to what?\" (then listen) \"If we take X out of the scope, I can bring it to $Y. Or we keep everything and I start next week. Which would you prefer?\"",
             why="You find out what they're really comparing, then you trade scope, never value."),
        dict(when="You need to raise your rates",
             dont="\"Sorry, I have to raise my prices...\"",
             say="\"Starting March 1, my rate for new projects will be $X. Because you've been with me from the start, your current rate stays the same through May.\"",
             why="A date, a number, a thank-you. No apology needed."),
        dict(when="An invoice is overdue",
             dont="\"Hey, sorry to bother you about this...\"",
             say="\"Hi Sam, invoice #104 for $1,200 was due on the 5th. Could you let me know the date it'll be paid? I've attached it again here.\"",
             why="Specific amount, specific date, one easy question."),
        dict(when="A client keeps adding requests",
             dont="\"Sure, I'll throw that in.\"",
             say="\"Great idea. That's outside what we agreed on, so I'll send a quick quote for it. Want me to finish the current scope first, or add this now?\"",
             why="Every \"quick extra\" gets a price. Scope creep stops on the first one."),
        dict(when="Someone asks you to work for exposure",
             dont="\"Hmm, let me think about it.\"",
             say="\"Thanks for thinking of me. I only take paid projects right now. My rate for this would be $X. If that works, I'd love to help.\"",
             why="Kind, clear and it leaves the door open for a paid yes."),
    ]),
    ("Sales and objections", "#7A5BA8", [
        dict(when="A prospect says \"send me some info\"",
             dont="\"Sure! I'll send it over.\"",
             say="\"Happy to. So I send what's actually useful, what's the main thing you'd want to see in it?\" (listen) \"Let's suppose it covers that. What would you want to happen next?\"",
             why="You find out what matters and agree on a next step before anything gets sent."),
        dict(when="They say \"we're happy with what we have\"",
             dont="\"But ours is so much better!\"",
             say="\"That's great, sounds like it's working. If you could change one thing about it, what would it be?\"",
             why="You agree first, then let them name the gap in their own words."),
        dict(when="They say \"I need to think about it\"",
             dont="\"Okay, take your time!\"",
             say="\"That makes sense, it's a real decision. What part do you want to think through? Sometimes it helps to talk it out now.\"",
             why="\"Think about it\" usually hides one specific worry. This brings it out."),
        dict(when="They say \"call me next quarter\"",
             dont="\"Sounds good, talk then!\"",
             say="\"Happy to. What would need to be true by then for this to be a priority?\" (listen) \"Let's put a time on the calendar now so it doesn't slip. Does the 14th at 10 work?\"",
             why="\"Later\" becomes a date, and you learn what's really blocking it."),
        dict(when="You're ready to ask for the close",
             dont="\"So, do you want to buy?\"",
             say="\"Based on everything you've told me, do you feel this could be the answer for you?\" (listen) \"Why do you feel it would?\"",
             why="They say the reasons out loud, so the decision is theirs, not a push from you."),
    ]),
]

assert sum(len(s[2]) for s in SECTIONS) == 25
