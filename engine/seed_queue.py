def build():
    out = []
    for p in POSTS:
        p = dict(p)
        p.setdefault("caption", p["hook"].split(".")[0] + ". 💬")
        p["tags"] = TAGS + ["#" + p["topic"].lower().replace(" ", "")]
        out.append(p)
    return out


